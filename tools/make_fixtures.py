"""Generate the io test fixtures in tests/fixtures/ from ONE synthetic spectrum.

Every fixture encodes the same known spectrum (or simple variants of it), so
the browser tests can assert exact point counts, first/last values and values
at given indices no matter which importer read the file. The ground truth is
written to tests/fixtures/io_truth.json; tests compare against that file
instead of re-deriving the formula.

    x_k = 100 + 4k cm-1, k = 0..825            (826 points, 100..3400)
    y(x) = 50 + 0.08 (x - 100)                 sloped background
         + 600 / (1 + ((x - 1350) / 22)^2)     D band (Lorentzian, HWHM 22)
         + 1000 / (1 + ((x - 1585) / 12)^2)    G band (tallest; max at x = 1584)
         + 450 / (1 + ((x - 2690) / 30)^2)     2D band

Multi-spectrum fixtures use the variants y1 = y, y2 = 0.5 y + 20,
y3 = 1.5 y - 10. All data is synthetic; nothing comes from a real instrument.

Usage (from the repo root; needs openpyxl and xlwt):
    python tools/make_fixtures.py

The output is deterministic: no randomness except a fixed LCG for the
ambiguous fixture, and the xlsx zip entries get a fixed timestamp.
"""
from __future__ import annotations

import io
import json
import struct
import zipfile
from datetime import datetime
from pathlib import Path

import openpyxl
import xlwt

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "tests" / "fixtures"
MAX_BYTES = 60_000

N = 826
X0, DX = 100.0, 4.0
PEAKS = [(1350.0, 600.0, 22.0), (1585.0, 1000.0, 12.0), (2690.0, 450.0, 30.0)]
VARIANTS = [(1.0, 0.0), (0.5, 20.0), (1.5, -10.0)]   # (scale, offset)
TRANSPOSED_STEP = 2     # transposed_rows.csv keeps every 2nd point
MAP_STEP = 16           # map_long.txt keeps every 16th point (cm-1 step 64)
MAP_COORDS = [(-10.0, -5.0), (10.0, -5.0), (-10.0, 5.0), (10.0, 5.0)]   # (X, Y) per map spectrum
MAP_SCALE = [1.0, 1.1, 1.2, 1.3]
JCAMP_YFACTOR = 0.01
SPC_EXP = 12            # 32-bit integer Y: y = int * 2^(exp-32); |y| < 2^(exp-1) = 2048
SPC_EXP2 = 11           # second subfile of multi_subfile.spc (|y2| < 1024)


def y_of(x: float) -> float:
    v = 50.0 + 0.08 * (x - 100.0)
    for c, h, g in PEAKS:
        v += h / (1.0 + ((x - c) / g) ** 2)
    return v


XS = [X0 + DX * k for k in range(N)]
YS = [y_of(x) for x in XS]


def variant(k: int, ys=YS):
    s, o = VARIANTS[k]
    return [s * v + o for v in ys]


def write_text(name: str, text: str, newline: str = "\n") -> None:
    data = text.replace("\n", newline).encode("utf-8")
    (OUT / name).write_bytes(data)


def f4(v: float) -> str:
    return f"{v:.4f}"


# ----------------------------------------------------------------- delimited text

def make_text_fixtures() -> None:
    rows = list(zip(XS, YS))
    write_text("spectrum_comma.csv",
               "Raman Shift (cm-1),Intensity\n" + "".join(f"{x:.1f},{f4(y)}\n" for x, y in rows))

    write_text("spectrum_semicolon_decimal_comma.csv",
               "Raman shift (cm-1);Intensity\n" +
               "".join(f"{x:.1f};{f4(y)}\n".replace(".", ",") for x, y in rows))

    write_text("spectrum.tsv",
               "Raman shift\tIntensity\n" + "".join(f"{x:.1f}\t{f4(y)}\n" for x, y in rows))

    # Renishaw WiRE: doubled tab in the header only, x DESCENDING, CRLF line ends.
    write_text("wire_export.txt",
               "#Wave\t\t#Intensity\n" + "".join(f"{x:.6f}\t{y:.6f}\n" for x, y in reversed(rows)),
               newline="\r\n")

    # Horiba LabSpec 6: '#key=\tvalue' header block, then tab-separated data, CRLF.
    head = [
        "#Acq. time (s)=\t10",
        "#Accumulations=\t2",
        "#Range (cm-¹)=\t100...3400",
        "#Windows=\t1",
        "#Laser (nm)=\t532.17",
        "#Grating=\t600 (500nm)",
        "#Instrument=\tSynthetic LabRAM (generated)",
        "#Date=\t06.10.2026 10:15",
    ]
    write_text("labspec_export.txt",
               "\n".join(head) + "\n" + "".join(f"{x:.3f}\t{f4(y)}\n" for x, y in rows),
               newline="\r\n")

    # Whitespace aligned, '#' and ';' comments (one inside the data), scientific
    # notation, trailing blank line.
    lines = ["# Synthetic spectrum, whitespace delimited", "; generated by tools/make_fixtures.py",
             "#   shift            intensity"]
    for k, (x, y) in enumerate(rows):
        if k == N // 2:
            lines.append("; --- second half ---")
        lines.append(f"  {x:.6e}    {y:.6e}")
    write_text("whitespace_comments.txt", "\n".join(lines) + "\n\n")

    ys = [variant(k) for k in range(3)]
    write_text("multi_column.csv",
               "Raman shift,Sample A,Sample B,Sample C\n" +
               "".join(f"{x:.1f},{f4(ys[0][i])},{f4(ys[1][i])},{f4(ys[2][i])}\n" for i, x in enumerate(XS)))

    write_text("index_first.csv",
               "Index,Raman Shift,Intensity\n" +
               "".join(f"{i + 1},{x:.1f},{f4(y)}\n" for i, (x, y) in enumerate(rows)))

    # Transposed: first row x, each further row one spectrum; no labels.
    sub = range(0, N, TRANSPOSED_STEP)
    trows = [",".join(f"{XS[i]:.1f}" for i in sub)]
    for k in range(3):
        v = variant(k)
        trows.append(",".join(f4(v[i]) for i in sub))
    write_text("transposed_rows.csv", "\n".join(trows) + "\n")

    # Renishaw map export: X, Y, Wave (descending within each spectrum), Intensity.
    msub = list(range(0, N, MAP_STEP))
    mlines = ["#X\t\t#Y\t\t#Wave\t\t#Intensity"]
    for (mx, my), s in zip(MAP_COORDS, MAP_SCALE):
        for i in reversed(msub):
            mlines.append(f"{mx:.6f}\t{my:.6f}\t{XS[i]:.6f}\t{s * YS[i]:.6f}")
    write_text("map_long.txt", "\n".join(mlines) + "\n", newline="\r\n")

    # Two non-monotonic columns: nothing says which (if any) is the axis.
    state = 12345
    amb = ["a,b"]
    for _ in range(40):
        vals = []
        for _ in range(2):
            state = (1103515245 * state + 12345) % 2**31
            vals.append(f"{state / 2**31 * 1000:.3f}")
        amb.append(",".join(vals))
    write_text("ambiguous.csv", "\n".join(amb) + "\n")

    # UTF-16 LE with BOM, non-ASCII header.
    text = "Raman shift (cm⁻¹)\tIntensité\r\n" + "".join(f"{x:.1f}\t{f4(y)}\r\n" for x, y in rows)
    (OUT / "utf16le.txt").write_bytes(b"\xff\xfe" + text.encode("utf-16-le"))


# ----------------------------------------------------------------- spreadsheets

def fixed_zip(path: Path) -> None:
    """Rewrite a zip with fixed entry timestamps so the xlsx is byte-reproducible."""
    src = zipfile.ZipFile(io.BytesIO(path.read_bytes()))
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as dst:
        for info in src.infolist():
            zi = zipfile.ZipInfo(info.filename, date_time=(2026, 1, 1, 0, 0, 0))
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = info.external_attr
            dst.writestr(zi, src.read(info.filename))
    path.write_bytes(buf.getvalue())


def make_spreadsheets() -> None:
    wb = openpyxl.Workbook()
    ws1 = wb.active
    ws1.title = "Sheet1"
    for x, y in zip(XS, YS):
        ws1.append([x, round(y, 4)])
    ws2 = wb.create_sheet("Sheet2")
    ws2.append(["Raman shift (cm-1)", "Intensity A", "Intensity B"])
    y2, y3 = variant(1), variant(2)
    for i, x in enumerate(XS):
        # Column C as text with a decimal comma, as a European Excel paste leaves it.
        ws2.append([x, round(y2[i], 4), f4(y3[i]).replace(".", ",")])
    ws3 = wb.create_sheet("Notes")
    ws3.append(["Synthetic workbook generated by tools/make_fixtures.py"])
    ws3.append(["Sample", "none (generated)"])
    ws3.append(["Accumulations", 3])
    ws3.append(["Sheet1 and Sheet2 hold the data; this sheet must be ignored."])
    fixed = datetime(2026, 1, 1)
    wb.properties.created = fixed
    wb.properties.modified = fixed
    path = OUT / "multi_sheet.xlsx"
    wb.save(path)
    fixed_zip(path)

    book = xlwt.Workbook()
    sh = book.add_sheet("Spectrum")
    sh.write(0, 0, "Raman shift / cm-1")
    sh.write(0, 1, "Intensity")
    for i, (x, y) in enumerate(zip(XS, YS)):
        sh.write(i + 1, 0, x)
        sh.write(i + 1, 1, round(y, 4))
    bio = io.BytesIO()
    book.save(bio)
    (OUT / "legacy.xls").write_bytes(bio.getvalue())


# ----------------------------------------------------------------- JCAMP-DX

# ASDF pseudo-digits (JCAMP-DX 4.24, McDonald & Wilks 1988, table 4):
#   SQZ  @ A-I (+0..+9)  a-i (-1..-9)   replaces sign + first digit of an ordinate
#   DIF  % J-R (+0..+9)  j-r (-1..-9)   same, for a difference from the previous ordinate
#   DUP  S-Z (1..8)  s (9)              repeat count of the previous token, incl. itself
SQZ_POS, SQZ_NEG = "@ABCDEFGHI", "@abcdefghi"
DIF_POS, DIF_NEG = "%JKLMNOPQR", "%jklmnopqr"
DUP_CH = "STUVWXYZs"


def _pseudo(v: int, pos: str, neg: str) -> str:
    s = str(abs(v))
    return (pos if v >= 0 else neg)[int(s[0])] + s[1:]


def sqz(v: int) -> str:
    return _pseudo(v, SQZ_POS, SQZ_NEG)


def dif(v: int) -> str:
    return _pseudo(v, DIF_POS, DIF_NEG)


def dup(n: int) -> str:
    s = str(n)
    return DUP_CH[int(s[0]) - 1] + s[1:]


def encode_difdup(xs: list[int], ys: list[int], maxlen: int = 80) -> list[str]:
    """(X++(Y..Y)) lines in DIFDUP form with Y checks.

    Each line starts with the abscissa of its first ordinate, written SQZ; the
    rest are DIF tokens, runs of equal differences collapsed with DUP. The last
    ordinate of a line is repeated (SQZ) as the first of the next line - the
    Y-value check readers must verify and drop.
    """
    n = len(ys)
    lines = []
    i = 0
    while True:
        line = f"{xs[i]}{sqz(ys[i])}"
        j = i
        while j + 1 < n:
            d = ys[j + 1] - ys[j]
            run = 1
            while j + 1 + run < n and ys[j + 1 + run] - ys[j + run] == d:
                run += 1
            tok = dif(d) + (dup(run) if run > 1 else "")
            if len(line) + len(tok) > maxlen:
                break
            line += tok
            j += run
        lines.append(line)
        if j + 1 >= n:
            break
        i = j
    return lines


def jcamp_header(title: str, version: str, extra: list[str]) -> list[str]:
    return [
        f"##TITLE={title}",
        f"##JCAMP-DX={version}",
        "##DATA TYPE=RAMAN SPECTRUM",
        "##ORIGIN=Raman Studio tools/make_fixtures.py (synthetic)",
        "##OWNER=public domain",
        "##$LASER WAVELENGTH=532",
        "##XUNITS=1/CM",
        "##YUNITS=ARBITRARY UNITS",
        *extra,
    ]


def make_jcamp() -> None:
    yi = [round(v / JCAMP_YFACTOR) for v in YS]
    xi = [int(x) for x in XS]
    common = [
        "##XFACTOR=1", f"##YFACTOR={JCAMP_YFACTOR}", f"##FIRSTX={XS[0]:g}", f"##LASTX={XS[-1]:g}",
        f"##DELTAX={DX:g}", f"##NPOINTS={N}", f"##FIRSTY={yi[0] * JCAMP_YFACTOR:.2f}",
        f"##MAXY={max(yi) * JCAMP_YFACTOR:.2f}", f"##MINY={min(yi) * JCAMP_YFACTOR:.2f}",
    ]
    affn = jcamp_header("Synthetic graphene spectrum (AFFN)", "4.24", common) + ["##XYDATA=(X++(Y..Y))"]
    for k in range(0, N, 10):
        affn.append(f"{xi[k]} " + " ".join(str(v) for v in yi[k:k + 10]))
    affn.append("##END=")
    write_text("spectrum_affn.jdx", "\n".join(affn) + "\n")

    comp = jcamp_header("Synthetic graphene spectrum (DIFDUP)", "4.24", common) + ["##XYDATA=(X++(Y..Y))"]
    comp += encode_difdup(xi, yi)
    comp.append("##END=")
    write_text("spectrum_compressed.jdx", "\n".join(comp) + "\n")

    pts = jcamp_header("Synthetic graphene spectrum (XYPOINTS)", "5.01", [
        "##XFACTOR=1", "##YFACTOR=1", f"##FIRSTX={XS[-1]:g}", f"##LASTX={XS[0]:g}", f"##NPOINTS={N}",
        "##XYPOINTS=(XY..XY)",
    ])
    pairs = [f"{x:.1f}, {f4(y)}" for x, y in zip(reversed(XS), reversed(YS))]   # descending x
    for k in range(0, N, 4):
        pts.append("; ".join(pairs[k:k + 4]))
    pts.append("##END=")
    write_text("xy_points.dx", "\n".join(pts) + "\n")


# ----------------------------------------------------------------- Thermo Galactic SPC
#
# New-format SPC (fversn 0x4B = little-endian), from the Galactic "SPC file
# format" spec / spc.h. All multi-byte fields little-endian.
#
# Main header, 512 bytes:
#   0   BYTE   ftflgs   flags: 0x01 TSPREC (16-bit Y), 0x02 TCGRAM, 0x04 TMULTI,
#                       0x08 TRANDM, 0x10 TORDRD, 0x20 TALABS, 0x40 TXYXYS, 0x80 TXVALS
#   1   BYTE   fversn   0x4B new LSB, 0x4C new MSB, 0x4D old format
#   2   BYTE   fexper   experiment type (11 = Raman)
#   3   char   fexp     Y exponent; 0x80 (-128) = IEEE float Y
#   4   DWORD  fnpts    points per subfile (TXYXYS: offset of subfile directory or 0)
#   8   double ffirst   first X (evenly spaced data)
#   16  double flast    last X
#   24  DWORD  fnsub    number of subfiles
#   28  BYTE   fxtype   X units (1 = cm-1, 3 = nm, 13 = Raman shift cm-1)
#   29  BYTE   fytype   Y units (4 = counts, 12 = intensity)
#   30  BYTE   fztype   Z units
#   31  BYTE   fpost    posting disposition
#   32  DWORD  fdate    min | hour<<6 | day<<11 | month<<16 | year<<20
#   36  char[9]   fres     resolution text
#   45  char[9]   fsource  instrument text
#   54  WORD   fpeakpt
#   56  float[8]  fspare
#   88  char[130] fcmnt    memo
#   218 char[30]  fcatxt   axis labels (TALABS), NUL separated
#   248 DWORD  flogoff  offset of the log block (0 = none)
#   252 DWORD  fmods
#   256 BYTE fprocs, 257 BYTE flevel, 258 WORD fsampin, 260 float ffactor,
#   264 char[48] fmethod, 312 float fzinc, 316 DWORD fwplanes, 320 float fwinc,
#   324 BYTE fwtype, 325 char[187] freserv                       -> 512 bytes
# Then: X array (float32[fnpts]) when TXVALS and not TXYXYS; then per subfile a
# 32-byte subheader, its own X array (float32[subnpts]) when TXYXYS, and Y:
#   float32 when the exponent is 0x80, else int32 (int16 with TSPREC) scaled
#   y = int * 2^(exp-32)  (2^(exp-16) for int16).
# Subheader, 32 bytes:
#   0 BYTE subflgs, 1 char subexp, 2 WORD subindx, 4 float subtime, 8 float subnext,
#   12 float subnois, 16 DWORD subnpts, 20 DWORD subscan, 24 float subwlevel, 28 char[4] subresv
# Log block at flogoff: 64-byte LOGSTC (DWORD logsizd, logsizm, logtxto, logbins,
# logdsks, char[44] spare) followed by "key=value\r\n" text at flogoff + logtxto.

TSPREC, TMULTI, TXYXYS, TXVALS = 0x01, 0x04, 0x40, 0x80


def spc_header(*, ftflgs: int, fexp: int, fnpts: int, ffirst: float, flast: float, fnsub: int,
               memo: str, logoff: int = 0, fxtype: int = 13, fytype: int = 4) -> bytes:
    h = bytearray(512)
    struct.pack_into("<BBBb", h, 0, ftflgs, 0x4B, 11, fexp)
    struct.pack_into("<Idd", h, 4, fnpts, ffirst, flast)
    struct.pack_into("<I", h, 24, fnsub)
    struct.pack_into("<BBBB", h, 28, fxtype, fytype, 0, 0)
    struct.pack_into("<I", h, 32, 0 | 12 << 6 | 6 << 11 | 10 << 16 | 2026 << 20)
    h[36:45] = b"4 cm-1\0\0\0"
    h[45:54] = b"SYNTH\0\0\0\0"
    m = memo.encode("ascii")[:129]
    h[88:88 + len(m)] = m
    struct.pack_into("<I", h, 248, logoff)
    return bytes(h)


def subheader(*, subexp: int, index: int, npts: int = 0, z: float = 0.0) -> bytes:
    sh = struct.pack("<BbHfffIIf4s", 0, subexp, index, z, 0.0, 0.0, npts, 1, 0.0, b"\0" * 4)
    assert len(sh) == 32
    return sh


def int_y(ys: list[float], exp: int) -> bytes:
    scale = 2.0 ** (32 - exp)
    return struct.pack(f"<{len(ys)}i", *[round(v * scale) for v in ys])


def log_block(text: str) -> bytes:
    body = text.encode("ascii") + b"\0"
    return struct.pack("<IIIII44s", 64 + len(body), 64 + len(body), 64, 0, 0, b"\0" * 44) + body


def make_spc() -> None:
    # Evenly spaced, 32-bit integer Y with exponent, log block with the laser line.
    data = subheader(subexp=SPC_EXP, index=0) + int_y(YS, SPC_EXP)
    logoff = 512 + len(data)
    head = spc_header(ftflgs=0, fexp=SPC_EXP, fnpts=N, ffirst=XS[0], flast=XS[-1], fnsub=1,
                      memo="Synthetic graphene spectrum (int32 Y, even X)", logoff=logoff)
    log = log_block("Laser Wavelength=785.0\r\nOperator=synthetic\r\nExposure Time (s)=1\r\n")
    (OUT / "spectrum_even.spc").write_bytes(head + data + log)

    # TXVALS: explicit float32 X array (descending), IEEE float Y.
    xs_desc = list(reversed(XS))
    ys_desc = list(reversed(YS))
    head = spc_header(ftflgs=TXVALS, fexp=-128, fnpts=N, ffirst=xs_desc[0], flast=xs_desc[-1], fnsub=1,
                      memo="Synthetic graphene spectrum (float Y, explicit X)", fytype=12)
    body = struct.pack(f"<{N}f", *xs_desc) + subheader(subexp=-128, index=0) + struct.pack(f"<{N}f", *ys_desc)
    (OUT / "spectrum_float_xy.spc").write_bytes(head + body)

    # Two subfiles, evenly spaced, int32 Y, each subfile with its own exponent.
    head = spc_header(ftflgs=TMULTI, fexp=SPC_EXP, fnpts=N, ffirst=XS[0], flast=XS[-1], fnsub=2,
                      memo="Synthetic multi-subfile SPC (variants 1 and 2)")
    body = (subheader(subexp=SPC_EXP, index=0, z=0.0) + int_y(variant(0), SPC_EXP) +
            subheader(subexp=SPC_EXP2, index=1, z=1.0) + int_y(variant(1), SPC_EXP2))
    (OUT / "multi_subfile.spc").write_bytes(head + body)


# ----------------------------------------------------------------- truth

def make_truth() -> None:
    truth = {
        "comment": "Ground truth for the io fixtures; generated by tools/make_fixtures.py.",
        "n": N, "x0": X0, "dx": DX,
        "peaks": [{"center": c, "height": h, "hwhm": g} for c, h, g in PEAKS],
        "variants": [list(v) for v in VARIANTS],
        "transposedStep": TRANSPOSED_STEP,
        "mapStep": MAP_STEP, "mapCoords": [list(c) for c in MAP_COORDS], "mapScale": MAP_SCALE,
        "jcampYFactor": JCAMP_YFACTOR,
        "spcExp": [SPC_EXP, SPC_EXP2],
        "x": XS,
        "y": YS,
    }
    (OUT / "io_truth.json").write_text(json.dumps(truth), encoding="utf-8")


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    make_text_fixtures()
    make_spreadsheets()
    make_jcamp()
    make_spc()
    make_truth()
    names = ["spectrum_comma.csv", "spectrum_semicolon_decimal_comma.csv", "spectrum.tsv", "wire_export.txt",
             "labspec_export.txt", "whitespace_comments.txt", "multi_column.csv", "index_first.csv",
             "transposed_rows.csv", "map_long.txt", "ambiguous.csv", "utf16le.txt", "multi_sheet.xlsx",
             "legacy.xls", "spectrum_affn.jdx", "spectrum_compressed.jdx", "xy_points.dx",
             "spectrum_even.spc", "spectrum_float_xy.spc", "multi_subfile.spc", "io_truth.json"]
    for name in names:
        size = (OUT / name).stat().st_size
        flag = "  TOO BIG" if size > MAX_BYTES else ""
        print(f"{name:40s} {size:7d} bytes{flag}")
        if flag:
            raise SystemExit(f"{name} exceeds {MAX_BYTES} bytes")


if __name__ == "__main__":
    main()
